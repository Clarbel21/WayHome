/**
 * Regenerate the ESP32 landmark bitmaps from the web app's SVGs.
 *
 *   CHROMIUM_PATH=/path/to/chrome.exe node firmware/tools/make_landmark_images.mjs
 *
 * Renders each built-in landmark at 360x200 in headless Chromium, converts the
 * pixels to RGB565 (little-endian, as LVGL 9 expects) and writes
 * firmware/wayhome-watch/landmark_images.cpp. The four stop names and their
 * order must match initialLandmarks in src/store.ts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const width = 360;
const height = 200;
const stops = [
  { id: "garden", svg: "garden.svg", name: "Community garden" },
  { id: "bakery", svg: "bakery.svg", name: "Neighborhood bakery" },
  { id: "library", svg: "library.svg", name: "Local library" },
  { id: "home", svg: "home.svg", name: "Home" },
];

const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_PATH || undefined,
  headless: true,
});
const page = await browser.newPage();
const rendered = [];

for (const stop of stops) {
  const svg = readFileSync(path.join(root, "public/images", stop.svg), "utf8");
  const dataUri = `data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}`;
  const pixels = await page.evaluate(
    async ({ uri, w, h }) => {
      const image = new Image();
      image.src = uri;
      await image.decode();
      const canvas = document.createElement("canvas");
      canvas.width = w;
      canvas.height = h;
      const ctx = canvas.getContext("2d", { willReadFrequently: true });
      ctx.drawImage(image, 0, 0, w, h);
      const rgba = ctx.getImageData(0, 0, w, h).data;
      const rgb565 = new Uint16Array(w * h);
      for (let i = 0; i < w * h; i += 1) {
        const r = rgba[i * 4];
        const g = rgba[i * 4 + 1];
        const b = rgba[i * 4 + 2];
        rgb565[i] = ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3);
      }
      return Array.from(rgb565);
    },
    { uri: dataUri, w: width, h: height },
  );
  if (pixels.length !== width * height) {
    throw new Error(`${stop.svg} rendered ${pixels.length} pixels`);
  }
  rendered.push({ ...stop, pixels });
  console.log(`${stop.svg}: ${pixels.length} RGB565 pixels`);
}

await browser.close();

const lines = [
  "// Generated by firmware/tools/make_landmark_images.mjs - do not edit by hand.",
  "// 360x200 RGB565 pixels, little-endian, for LVGL 9 on the ESP32-S3.",
  "// Stop order matches initialLandmarks in src/store.ts.",
  '#include "landmark_images.h"',
  "",
];

for (const stop of rendered) {
  lines.push(`alignas(4) const uint16_t wh_${stop.id}_pixels[${width * height}] = {`);
  for (let i = 0; i < stop.pixels.length; i += 8) {
    const values = stop.pixels
      .slice(i, i + 8)
      .map((v) => `0x${v.toString(16).padStart(4, "0").toUpperCase()}`)
      .join(", ");
    lines.push(`  ${values},`);
  }
  lines.push("};");
  lines.push(`const lv_image_dsc_t wh_${stop.id}_img = {`);
  lines.push("  {LV_IMAGE_HEADER_MAGIC, LV_COLOR_FORMAT_RGB565, 0, 360, 200, 720, 0},");
  lines.push(`  sizeof(wh_${stop.id}_pixels),`);
  lines.push(`  (const uint8_t *)wh_${stop.id}_pixels,`);
  lines.push("  nullptr,");
  lines.push("  nullptr,");
  lines.push("};");
  lines.push("");
}

lines.push("const LandmarkImage whLandmarkImages[WH_LANDMARK_COUNT] = {");
for (const stop of rendered) {
  lines.push(`  {"${stop.name}", &wh_${stop.id}_img},`);
}
lines.push("};");
lines.push("");

writeFileSync(
  path.join(root, "firmware/wayhome-watch/landmark_images.cpp"),
  lines.join("\n"),
);
console.log("wrote firmware/wayhome-watch/landmark_images.cpp");
