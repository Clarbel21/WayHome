/**
 * Render the web watch's home-tile emoji (🏠 📞 💬 🎮) for the ESP32.
 *
 *   CHROMIUM_PATH=/path/to/chrome node firmware/tools/make_emoji_images.mjs
 *
 * Needs the Noto Color Emoji font. Writes firmware/wayhome-watch/
 * emoji_images.cpp: 76x76 RGB565A8 (colour plane, then alpha plane) so the
 * emoji sit on any tile colour.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const S = 76;
const emoji = [
  ["home", "🏠"],
  ["call", "📞"],
  ["talk", "💬"],
  ["game", "🎮"],
];
const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_PATH || undefined,
  headless: true,
});
const page = await browser.newPage();
await page.setContent(
  `<span style="font-family:'Noto Color Emoji'">🏠📞💬🎮</span>`,
);
await page.evaluate(() => document.fonts.ready);
const out = [
  "// Generated by firmware/tools/make_emoji_images.mjs - do not edit by hand.",
  `// ${S}x${S} RGB565A8 home-tile emoji, same as the web watch.`,
  '#include "emoji_images.h"',
  "",
];
for (const [id, ch] of emoji) {
  const { rgb, alpha } = await page.evaluate(
    ({ ch, S }) => {
      const c = document.createElement("canvas");
      c.width = S;
      c.height = S;
      const ctx = c.getContext("2d", { willReadFrequently: true });
      ctx.textAlign = "center";
      ctx.textBaseline = "middle";
      ctx.font = `${Math.round(S * 0.82)}px 'Noto Color Emoji'`;
      ctx.fillText(ch, S / 2, S / 2 + S * 0.04);
      const d = ctx.getImageData(0, 0, S, S).data;
      const rgb = [];
      const alpha = [];
      for (let i = 0; i < S * S; i++) {
        // getImageData is not premultiplied: colour and alpha are separate.
        const a = d[i * 4 + 3];
        const r = d[i * 4];
        const g = d[i * 4 + 1];
        const b = d[i * 4 + 2];
        rgb.push(((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3));
        alpha.push(a);
      }
      return { rgb, alpha };
    },
    { ch, S },
  );
  const bytes = [];
  for (const v of rgb) bytes.push(v & 0xff, v >> 8);
  bytes.push(...alpha);
  out.push(`alignas(4) static const uint8_t wh_emoji_${id}_data[${bytes.length}] = {`);
  for (let i = 0; i < bytes.length; i += 16)
    out.push("  " + bytes.slice(i, i + 16).map((b) => `0x${b.toString(16).padStart(2, "0")}`).join(", ") + ",");
  out.push("};");
  out.push(`const lv_image_dsc_t wh_emoji_${id}_img = {`);
  out.push(`  {LV_IMAGE_HEADER_MAGIC, LV_COLOR_FORMAT_RGB565A8, 0, ${S}, ${S}, ${S * 2}, 0},`);
  out.push(`  sizeof(wh_emoji_${id}_data),`);
  out.push(`  wh_emoji_${id}_data,`);
  out.push("  nullptr,");
  out.push("  nullptr,");
  out.push("};");
  out.push("");
  console.log(`${id} ok`);
}
await browser.close();
writeFileSync(path.join(root, "firmware/wayhome-watch/emoji_images.cpp"), out.join("\n"));
console.log("wrote firmware/wayhome-watch/emoji_images.cpp");
