/**
 * Regenerate the ESP32 Game pictures (G1 places without name plaques, G2
 * family faces) from the web app's quiz SVGs.
 *
 *   CHROMIUM_PATH=/path/to/chrome node firmware/tools/make_quiz_images.mjs
 *
 * Renders each SVG at 230x140 (the 360x220 artwork scaled down), converts to
 * RGB565 little-endian for LVGL 9 and writes firmware/wayhome-watch/
 * quiz_images.cpp. Order: places as in src/game/landmarks.ts, faces as in
 * initialFamily (src/store.ts).
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const W = 230;
const H = 140;
const pictures = [
  "garden",
  "bakery",
  "library",
  "home",
  "face-jamie",
  "face-sam",
  "face-mei",
];

const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_PATH || undefined,
  headless: true,
});
const page = await browser.newPage();
const out = [
  "// Generated by firmware/tools/make_quiz_images.mjs - do not edit by hand.",
  `// ${W}x${H} RGB565 pixels, little-endian, for LVGL 9 on the ESP32-S3.`,
  '#include "quiz_images.h"',
  "",
];
for (const id of pictures) {
  const svg = readFileSync(path.join(root, "public/images", `quiz-${id}.svg`), "utf8");
  const uri = `data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}`;
  const px = await page.evaluate(
    async ({ uri, w, h }) => {
      const img = new Image();
      img.src = uri;
      await img.decode();
      const c = document.createElement("canvas");
      c.width = w;
      c.height = h;
      const ctx = c.getContext("2d", { willReadFrequently: true });
      ctx.fillStyle = "#f7f7eb";
      ctx.fillRect(0, 0, w, h);
      ctx.drawImage(img, 0, 0, w, h);
      const d = ctx.getImageData(0, 0, w, h).data;
      const v = new Array(w * h);
      for (let i = 0; i < w * h; i++)
        v[i] = ((d[i * 4] & 0xf8) << 8) | ((d[i * 4 + 1] & 0xfc) << 3) | (d[i * 4 + 2] >> 3);
      return v;
    },
    { uri, w: W, h: H },
  );
  const name = id.replace("-", "_");
  out.push(`alignas(4) static const uint16_t wh_quiz_${name}_px[${W * H}] = {`);
  for (let i = 0; i < px.length; i += 12)
    out.push(
      "  " +
        px
          .slice(i, i + 12)
          .map((x) => `0x${x.toString(16).padStart(4, "0").toUpperCase()}`)
          .join(", ") +
        ",",
    );
  out.push("};");
  out.push(`const lv_image_dsc_t wh_quiz_${name}_img = {`);
  out.push(`  {LV_IMAGE_HEADER_MAGIC, LV_COLOR_FORMAT_RGB565, 0, ${W}, ${H}, ${W * 2}, 0},`);
  out.push(`  sizeof(wh_quiz_${name}_px),`);
  out.push(`  (const uint8_t *)wh_quiz_${name}_px,`);
  out.push("  nullptr,");
  out.push("  nullptr,");
  out.push("};");
  out.push("");
  console.log(`quiz-${id}.svg ok`);
}
await browser.close();
writeFileSync(path.join(root, "firmware/wayhome-watch/quiz_images.cpp"), out.join("\n"));
console.log("wrote firmware/wayhome-watch/quiz_images.cpp");
